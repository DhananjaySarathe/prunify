/**
 * Builds `ai_prompt.tsx` for the analyzed project: a copy-paste prompt for
 * Cursor / Copilot / other agents, with safety guardrails for prunify reports.
 */

export interface AgentPromptMeta {
  prunifyVersion: string
  generatedAtIso: string
  projectRootDisplay: string
  reportsDirDisplay: string
}

function buildPromptBody(meta: AgentPromptMeta): string {
  const { prunifyVersion, generatedAtIso, projectRootDisplay, reportsDirDisplay } = meta

  return `You are assisting with a **careful, incremental** cleanup of a TypeScript/JavaScript codebase.

## Context (prunify ${prunifyVersion})

- **Project root:** ${projectRootDisplay}
- **Reports folder:** ${reportsDirDisplay}
- **Report generated (this prompt file):** ${generatedAtIso}

The user has run **prunify** (static analysis). The reports are hints, not ground truth. **False positives are common.**

## Attach these files to the chat (if they exist)

From \`${reportsDirDisplay}\`:

| File | What it means |
|------|----------------|
| **dead-code.txt** | Orphan files (safe / transitive), dead exports, sizes. **--delete** uses this for whole-file removal. |
| **circular.txt** | Import cycles — usually **refactor**, not delete. |
| **dupes.md** | Repeated code **blocks** — merge only after **semantic** review. |
| **deps.md** | package.json vs imports — **unused** / **missing** / dev issues. |
| **assets.md** (+ **assets.txt**) | Unreferenced files under **public/** — **--delete-assets** uses the report. |

If a file is missing, skip that section of work.

---

## Mandatory safety rules (do not skip)

1. **No bulk deletes.** Work in small batches; one PR or one chat turn per logical change.
2. **Dead code — files:** Only delete files listed under **Safe to delete** (or explicitly marked removable in dead-code.txt) **after** you grep/search for dynamic imports, \`require(variable)\`, string-based paths, Next.js \`app/\`/\`pages/\` conventions, and config references.
3. **Dead code — exports:** Removing an export can break external consumers or barrels. After removal, run typecheck; fix barrel \`index.ts\` re-exports.
4. **Barrel files (\`index.ts\`):** A file may be "used" only via \`export * from './X'\`. Do not delete leaf modules until importers and barrels are updated.
5. **Transitively dead:** Deletion order matters — follow the report chains; remove importers before importers-only-used-by-dead-code where applicable.
6. **Circular imports:** Prefer extracting shared code or inverting dependencies; **do not** "fix" by deleting arbitrary cycle members.
7. **dupes.md:** Identical text ≠ identical behavior (closures, imports, generics). **Merge duplicates only** when you can prove equivalence; prefer extracting a shared function with tests.
8. **deps.md — unused:** prunify scans **src/** imports only. Packages may still be used in **root config**, **scripts**, **CSS**, **tests outside src**, **Next.js** files outside \`src/\`, or **CLI**. Confirm with repo-wide search before \`npm uninstall\`.
9. **deps.md — missing:** May be transitive or tooling; verify before adding duplicates.
10. **assets:** URLs may be built at runtime, come from CMS, or live in strings prunify does not see. Confirm with search before deleting from **public/**.

---

## Suggested order (lowest risk first)

1. **Verify deps.md** — search the whole repo; adjust package.json only with evidence.
2. **Dead exports** — remove unused exports / tidy barrels; typecheck after each batch.
3. **Safe-to-delete files** — small batches; run build after.
4. **Unused assets** — after string search in app and config.
5. **dupes.md** — last; highest judgment; add tests when merging.

---

## After every batch

- Run **lint** and **typecheck** (and **tests** if available).
- Run **production build** before declaring done.
- If something fails, **revert** that batch and narrow the change.

---

## What not to do

- Do not delete **pages**, **app routes**, **middleware**, or framework entry files unless the user explicitly asks and you verified they are unused.
- Do not remove packages because deps.md says "unused" without a repo-wide check.
- Do not merge duplicate blocks from dupes.md without reading surrounding code.

When uncertain, **list the risk** and ask the user to confirm before editing.`
}

/**
 * Returns full `.tsx` file contents: default export string for agents + header comments.
 */
export function buildAiPromptTsx(meta: AgentPromptMeta): string {
  const body = buildPromptBody(meta)
  const literal = JSON.stringify(body)

  return `/* eslint-disable */
/**
 * Auto-generated by prunify ${meta.prunifyVersion} — ${meta.generatedAtIso}
 * Do not edit by hand; re-run \`npx prunify\` to refresh.
 *
 * **For Cursor / Copilot:** attach the files listed inside PRUNIFY_CLEANUP_AGENT_PROMPT
 * (from prunify-reports/), then paste the prompt or use @-mention on those files plus this file.
 */
export const PRUNIFY_CLEANUP_AGENT_PROMPT = ${literal} as const

export default PRUNIFY_CLEANUP_AGENT_PROMPT
`
}
